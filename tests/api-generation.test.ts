// Generation is offline and deterministic. Missing, changed and extra output,
// or fixture bytes no longer vouched for by provenance, are refusals, not fixes.
import assert from "node:assert/strict";
import test from "node:test";
import { mkdtemp, cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { compare, generate, verifySource } from "../scripts/api";
import { createApi } from "../src/effects/api";
import { documentedRoute } from "../src/generated/routes.gen";

test("two generations agree and every class of generated drift is refused without repair", async () => {
  const temporary = await mkdtemp(join(tmpdir(), "api-generation-"));
  try {
    const first = join(temporary, "first");
    const second = join(temporary, "second");
    await generate(process.cwd(), first);
    await generate(process.cwd(), second);
    await compare(first, second);
    const file = join(second, "types.gen.ts");
    const original = await readFile(file);
    await writeFile(file, "// changed\n");
    await assert.rejects(compare(first, second), /types.gen.ts: generated bytes differ/);
    assert.equal(await readFile(file, "utf8"), "// changed\n");
    await rm(file);
    await assert.rejects(compare(first, second), /types.gen.ts: missing or extra/);
    await writeFile(file, original);
    await writeFile(join(second, "obsolete.ts"), "// stale\n");
    await assert.rejects(compare(first, second), /obsolete.ts: missing or extra/);
    const root = join(temporary, "fixture");
    await mkdir(join(root, "testdata"), { recursive: true });
    for (const name of ["openapi.json", "openapi.source.json"])
      await cp(join("testdata", name), join(root, "testdata", name));
    await verifySource(root);
    await writeFile(join(root, "testdata/openapi.json"), "{}\n");
    await assert.rejects(verifySource(root), /provenance SHA-256 mismatch/);
  } finally {
    await rm(temporary, { recursive: true, force: true });
  }
});

test("the read map names every key the pin answers a read of, and no other", async () => {
  // A pack declares one "module/entity" and the read that answers it; this is the
  // inventory that decides both. Re-derived from the document here, so a generator
  // that dropped a key, invented one or printed a GET whose answer is not a body
  // fails by name rather than by a screen that drew nothing on a device.
  const temporary = await mkdtemp(join(tmpdir(), "entry-reads-"));
  try {
    await generate(process.cwd(), temporary);
    const [printed, operations] = await Promise.all([
      readFile(join(temporary, "entries.gen.ts"), "utf8"),
      readFile(join(temporary, "operations.gen.ts"), "utf8"),
    ]);
    const map = new Map<string, string[]>();
    for (const row of printed.matchAll(/^\s*"([^"]+)": \[([^\]]*)\],$/gm))
      map.set(
        row[1]!,
        row[2]!
          .split(",")
          .map((name) => name.trim().replaceAll('"', ""))
          .filter((name) => name !== ""),
      );
    const answered = new Map<string, string[]>();
    const document = JSON.parse(await readFile("testdata/openapi.json", "utf8")) as {
      paths: Record<string, Record<string, unknown>>;
    };
    for (const methods of Object.values(document.paths)) {
      for (const [method, entry] of Object.entries(methods)) {
        const call = entry as {
          operationId?: string;
          responses?: Record<string, { content?: Record<string, unknown> }>;
        };
        if (method !== "get" || !call.operationId) continue;
        const words = call.operationId.split("-");
        if (words.length < 2) continue;
        if (
          !Object.entries(call.responses ?? {}).some(
            ([status, response]) =>
              /^2\d\d$/.test(status) && response.content?.["application/json"],
          )
        )
          continue;
        const pair = `${words[0]}/${words[1]}`;
        const name = call.operationId.replace(/-([a-z])/g, (_, letter: string) =>
          letter.toUpperCase(),
        );
        assert.ok(
          operations.includes(`${name}: (`),
          `${name}: printed as a read of ${pair} with no generated method`,
        );
        answered.set(pair, [...(answered.get(pair) ?? []), name].sort());
      }
    }
    assert.deepEqual(
      new Map([...map.entries()].sort()),
      new Map(
        [...answered.entries()]
          .sort(([a], [b]) => (a < b ? -1 : 1))
          .map(([pair, names]) => [pair, names]),
      ),
    );
    assert.ok(map.get("task/task")?.includes("taskTaskRead"));
    assert.ok(
      !map.has("note/note"),
      "the golden catalogue's module is outside the public document",
    );
  } finally {
    await rm(temporary, { recursive: true, force: true });
  }
});

test("the pin answers the counts door, and answers it with numbers only", async () => {
  // A path the document does not print is refused before the wire, so "the phone may
  // ask" is a fact about the pin and not about a screen: it is checked here, where the
  // generated route table and the generated validator are the subjects.
  const route = documentedRoute("GET", "/api/v1/app/summary");
  assert.ok(route);
  assert.equal(route.json, true);
  assert.deepEqual(route.statuses, [200]);
  const answering = (body: unknown) =>
    createApi(
      "https://counts.test",
      (async () =>
        new Response(JSON.stringify(body), {
          headers: { "Content-Type": "application/json" },
        })) as typeof fetch,
    ).operations;
  const summary = (
    await answering({
      asOf: "2026-07-18T09:00:00Z",
      entries: [
        {
          module: "note",
          entity: "note",
          total: 128,
          highlight: 4,
          trend: {
            field: "createdAt",
            days: [{ day: "2026-07-17", count: 3 }],
          },
        },
      ],
    }).appSummary({})
  ).data;
  assert.equal(summary.entries?.[0]?.total, 128);
  assert.equal(summary.entries?.[0]?.highlight, 4);
  assert.equal(summary.entries?.[0]?.trend?.days?.[0]?.count, 3);
  // A number that is not a number is refused by the generated validator, so a body
  // this build cannot read becomes one refusal and never a row with a blank in it.
  await assert.rejects(
    answering({
      asOf: "2026-07-18T09:00:00Z",
      entries: [{ module: "note", entity: "note", total: "many" }],
    }).appSummary({}),
    /failed validation/,
  );
  // An absent number stays absent: nothing here turns "nobody answered" into zero.
  const quiet = (
    await answering({
      asOf: "2026-07-18T09:00:00Z",
      entries: [{ module: "note", entity: "note" }],
    }).appSummary({})
  ).data;
  assert.equal(quiet.entries?.[0]?.total, undefined);
  assert.equal(quiet.entries?.[0]?.highlight, undefined);
});
