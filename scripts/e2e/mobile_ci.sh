#!/usr/bin/env bash
# The CI half of the device journey: a served kernel, a database of its own, one
# tenant and one administrator, and this repository's flows at the end of them.
#
#   PK_KERNEL_BIN=<built binary> scripts/e2e/mobile_ci.sh out/apk/release/app-debug-signed.apk
#   scripts/e2e/mobile_ci.sh --probe        # what this host owes, and where it was found
#   scripts/e2e/mobile_ci.sh --kernel-pin   # which kernel commit the fixtures agree on
#
# It is platformkit's scripts/mobile_e2e.sh:128-206 adapted, copied and cited:
# the same database of its own created here and dropped in a trap that runs
# whichever step failed, the same configuration keys, the same
# `bootstrap --tenant e2e --host localhost --language pt-PT`, the same
# serve-and-wait on /health with the log printed when the process died — and, where
# the copy had dropped it, the refusal that ends the run when the sixty turns are
# spent and nothing was answered, so a server that never bound is never reported as
# thirteen journeys that failed. What is
# new here is where the binary comes from: this repository has no Go module and
# no toolchain, so the job builds it — from the commit this repository's own
# provenance records already name. testdata/catalog.source.json and
# testdata/openapi.source.json each carry an upstream.commit, and those are the
# bytes every screen here is derived from and every generated client is written
# against, so building that object is what makes the server the flows write
# through be the server the fixtures describe. No variable names that commit and
# nothing is downloaded by a tag: --kernel-pin reads both records, refuses by
# name when either is missing or does not hold forty hex characters, and refuses
# naming both when they disagree, because then the fixtures are not one build's.
# What the job hands back is the binary that build produced, in PK_KERNEL_BIN.
#
# The kernel's own README records the cost of this shape for its own copy
# (e2e/maestro/README.md:104-118: 56 identical non-comment lines, neither script
# sourcing the other, "until somebody lifts it into an owner of its own"). The
# cost is stated here rather than hidden: run.sh and this script are that copy,
# and every line either prints names the repository's own script.
#
# Nothing here is quiet. A missing tool, a missing /dev/kvm or a kernel the
# provenance records cannot name exits non-zero and names the missing piece; a
# journey that silently skipped would leave the coverage the README quotes looking
# like a number nobody earned.
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$root"
. "$(dirname "${BASH_SOURCE[0]}")/tools.sh"

# --probe is the CI job's first step: the search above, the refusal, and the path
# of everything found. It writes the directories it searched to $GITHUB_PATH so
# the step that boots the emulator has adb and emulator on its PATH — the kernel's
# job exports PATH inside the probe step alone and re-searches in the harness,
# which works but leaves the next reader guessing which shell had which PATH.
if [ "${1:-}" = "--probe" ]; then
  pk_tools mobile_ci adb emulator maestro docker psql python3 curl keytool ||
    {
      echo "  Label: pkit-ci-android. Either the runner image gains them or the" >&2
      echo "  journey moves to a runner that has them; it does not get skipped." >&2
      exit 1
    }
  [ -r /dev/kvm ] || {
    echo "mobile_ci: /dev/kvm is not readable, so no emulator boots here." >&2
    exit 1
  }
  # A debug keystore is generated by whoever needs one and is never committed, so
  # what is refused is the inability to have one, not its absence.
  [ -f "$HOME/.android/debug.keystore" ] || [ -w "$HOME" ] || {
    echo "mobile_ci: no debug keystore and no writable \$HOME to make one in." >&2
    exit 1
  }
  adb version | head -1
  adb devices
  emulator -version 2>/dev/null | head -3 || true
  if [ -n "${GITHUB_PATH:-}" ]; then
    for dir in $_pk_tool_paths; do printf '%s\n' "$dir" >>"$GITHUB_PATH"; done
  fi
  echo "mobile_ci: this host can run a device journey"
  exit 0
fi

# pk_kernel_pin prints, alone on stdout, the kernel commit the two provenance
# records agree on, and refuses by name what stops there being one: a record that
# is not there, an upstream.commit that is not a full object id, or two records
# that name different builds. The commit is forty hex characters because a commit,
# unlike a branch or a tag, cannot move under the build made from it.
pk_kernel_pin() {
  pk_tools mobile_ci python3 >/dev/null || return 1
  python3 - <<'PIN'
import json
import re
import sys

names = ["testdata/catalog.source.json", "testdata/openapi.source.json"]
pins = {}
for name in names:
    try:
        with open(name) as handle:
            record = json.load(handle)
    except OSError as error:
        print(f"mobile_ci: {name} cannot be read: {error}", file=sys.stderr)
        sys.exit(1)
    except ValueError as error:
        print(f"mobile_ci: {name} is not JSON: {error}", file=sys.stderr)
        sys.exit(1)
    upstream = record.get("upstream") if isinstance(record, dict) else None
    commit = upstream.get("commit") if isinstance(upstream, dict) else None
    if not isinstance(commit, str) or not re.fullmatch(r"[0-9a-f]{40}", commit):
        print(
            f"mobile_ci: {name} names no kernel to serve: upstream.commit is not a full "
            "forty-character object id, and anything looser is a ref somebody can move.",
            file=sys.stderr,
        )
        sys.exit(1)
    pins[name] = commit
if len(set(pins.values())) > 1:
    print(
        "mobile_ci: the provenance records name different kernel builds: "
        + ", ".join(f"{name} {commit[:12]}" for name, commit in pins.items())
        + ". The journey serves one build; re-pin one fixture with its own refresh.",
        file=sys.stderr,
    )
    sys.exit(1)
sys.stdout.write(next(iter(pins.values())) + "\n")
PIN
}

# --kernel-pin is the job's answer to "which commit, then": the checkout step that
# follows it has nothing but a step output to work from, so this prints the object
# id and nothing beside it.
if [ "${1:-}" = "--kernel-pin" ]; then
  pk_kernel_pin
  exit 0
fi

apk="${1:?the verification APK to install (make apk ABIS=x86_64 PROFILE=ci && make apk-debug-sign)}"
port="${PLATFORMKIT_MOBILE_PORT:-8098}"
admin_url="${PLATFORMKIT_TEST_ADMIN_URL:?the owner connection; the job exports it}"
app_url="${PLATFORMKIT_TEST_DATABASE_URL:?the application connection; the job exports it}"
export PK_MOBILE_REPORT="${PK_MOBILE_REPORT:-e2e/out/report.xml}"
database="platformkit_mobile_$(date +%s)_${RANDOM}_$$"

# The pin, before anything is copied, migrated or started. This is the kernel's
# argument (scripts/mobile_e2e.sh:31-41) with a different artifact at the end of
# it: what has to be fixed is the object the server was compiled from, and here it
# is fixed by the same records that vouch for the fixtures — so a run cannot serve
# a kernel newer than the catalog its screens were derived from.
pin="$(pk_kernel_pin)" || exit 1
kernel="${PK_KERNEL_BIN:-}"
if [ -z "$kernel" ]; then
  echo "mobile_ci: PK_KERNEL_BIN names no kernel binary to serve. The job builds ${pin} — this repository holds no Go toolchain — and exports the file that build wrote; serving something it cannot name is not a test." >&2
  exit 1
fi
if [ ! -x "$kernel" ]; then
  echo "mobile_ci: PK_KERNEL_BIN=$kernel is not an executable file; the job builds ${pin} and exports what go build wrote." >&2
  exit 1
fi
# The served kernel's vocabulary, named by the job and never guessed here: what a
# writable resource is, and which lifecycle command to run to its end. run.sh
# states the contract again to whoever runs it alone, in the same words.
for name in MODULE ENTITY KNOWN VERB VERB_FIELD VERB_TITLE DUE_FIELD STATUS_FIELD STATUS_VALUE; do
  [ -n "${!name:-}" ] || {
    echo "mobile_ci: $name names nothing; the job names the served kernel's vocabulary." >&2
    exit 1
  }
done
pk_tools mobile_ci psql python3 curl || exit 1

# A URL with the database swapped for this run's own: everything else — host,
# port, credentials, parameters — is what the job already uses, so a deployment
# that needs an sslmode keeps it. Copied from platformkit's scripts/mobile_e2e.sh
# with its reasoning: a PostgreSQL URL is scheme://user:pass@host:port/name with
# optional ?params, so the name is the last path segment and nothing else needs
# parsing.
swap() {
  python3 - "$1" "$2" <<'SWAP'
import sys

url, name = sys.argv[1], sys.argv[2]
head, _, query = url.partition("?")
if "://" not in head or "/" not in head.split("://", 1)[1]:
    print("mobile_ci: invalid PostgreSQL URL", file=sys.stderr)
    sys.exit(1)
cut = head.rindex("/")
sys.stdout.write(head[:cut] + "/" + name + (("?" + query) if query else ""))
SWAP
}
psql_admin() { psql "$(swap "$admin_url" postgres)" -v ON_ERROR_STOP=1 -q "$@"; }

work="$(mktemp -d)"
app_pid=""
created=false
cleanup() {
  status=$?
  if [ -n "$app_pid" ]; then
    kill "$app_pid" 2>/dev/null || true
    wait "$app_pid" 2>/dev/null || true
  fi
  if $created; then
    psql_admin -c "DROP DATABASE $database WITH (FORCE);" >/dev/null ||
      echo "mobile_ci: could not remove $database" >&2
  fi
  rm -rf "$work"
  return "$status"
}
trap cleanup EXIT

# The binary comes into this run's own directory rather than being exec'd where the
# job left it: the journey then holds one copy of one build, and the `rm -rf` in the
# trap is the only thing that can remove it.
echo "mobile_ci: the kernel the job built from ${pin}"
cp "$kernel" "$work/platformkit"
chmod +x "$work/platformkit"

echo "mobile_ci: a database of its own"
psql_admin -c "CREATE DATABASE $database;" >/dev/null
created=true
# The role exists (scripts/e2e/postgres-role.sql made it); the grants are per
# database, so a fresh one needs them again.
psql "$(swap "$admin_url" "$database")" -v ON_ERROR_STOP=1 -q \
  -c "GRANT USAGE ON SCHEMA public TO platformkit_app;" \
  -c "ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO platformkit_app;" \
  -c "ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO platformkit_app;"

# The key the served kernel seals its enrolled factors with, generated before the
# config that names it: this script runs under `set -u`, so a value read at the
# line where it is written would abort the whole harness at the config instead of
# telling anyone why no factor route exists. Generated per run, written to the
# config and nowhere else: it has no life beyond these minutes, which is why
# generating it beats naming one. Without it the auth module mounts no factor
# route at all, and the check after the server is up is what says so — before the
# emulator boots, not forty minutes into a journey. python3 rather than openssl
# because it is already a tool this script demands.
factor_key="$(python3 -c 'import secrets; print(secrets.token_hex(32))')"
# The kernel composes outbound webhooks and refuses to start without the key that wraps an endpoint's signing
# secret: thirty-two bytes of this run's own, as platformkit's own journey writes, and nothing verifies a delivery
# signed with them.
webhook_key="$(python3 -c 'import secrets; print(secrets.token_hex(16))')"
app_dsn="$(swap "$app_url" "$database")"
migrate_dsn="$(swap "$admin_url" "$database")"
cat >"$work/config.yaml" <<YAML
server:
  addr: ":$port"
  public_host: "localhost:$port"
  docs: false
database:
  url: "$app_dsn"
  migrate_url: "$migrate_dsn"
nats:
  url: "${PLATFORMKIT_TEST_NATS_URL:-nats://localhost:4222}"
log:
  level: "warn"
audit:
  retention_days: 365
auth:
  factor_key: "$factor_key"
webhook:
  secret_key: "$webhook_key"
files:
  dir: "$work/files"
YAML

password="mobile-$(date +%s)-password"
factor_email="factor@e2e.test"
factor_password="mobile-$(date +%s)-factor"
# The sentence modules/auth answers a right password with when the account also
# holds a factor. Read from the phone's own copy (src/core/signInOutcome.ts)
# rather than typed again here: the phone's whole rule is this sentence, and a
# harness that carried its own spelling would agree with itself while the two
# drifted apart.
factor_sentence="$(python3 - <<'SENTENCE'
import pathlib
import re
import sys

source = pathlib.Path("src/core/signInOutcome.ts").read_text()
match = re.search(r'FACTOR_REQUIRED_DETAIL =\s*\n?\s*"((?:[^"\\]|\\.)*)"', source)
if not match:
    sys.exit("mobile_ci: src/core/signInOutcome.ts states no factor sentence to prove against")
sys.stdout.write(match.group(1))
SENTENCE
)"
# The device reaches the server through run.sh's `adb reverse` below, so the
# address it is told to talk to is the device's own localhost. --language is the
# tenant's own declaration, as the kernel harness writes it: a tenant created
# without a second language is served in one. The copy a phone shows comes from
# the device's locale, not this value, so the English-speaking flows are
# unaffected by it either way.
run_app() {
  for variable in "${!PLATFORMKIT_@}"; do unset "$variable"; done
  export PLATFORMKIT_BOOTSTRAP_PASSWORD="$password"
  exec "$work/platformkit" "$@"
}
echo "mobile_ci: one tenant and one administrator"
(run_app bootstrap --config "$work/config.yaml" \
  --tenant e2e --host localhost --name "End to end" --admin-email admin@e2e.test \
  --language pt-PT) >/dev/null

if command -v ss >/dev/null && ss -ltn 2>/dev/null | grep -q ":$port "; then
  echo "mobile_ci: something is already listening on $port; set PLATFORMKIT_MOBILE_PORT." >&2
  exit 1
fi

echo "mobile_ci: serving on $port"
run_app run --config "$work/config.yaml" >"$work/app.log" 2>&1 &
app_pid=$!
served=false
for _ in $(seq 1 60); do
  if curl -fsS "http://localhost:$port/health" >/dev/null 2>&1; then
    served=true
    break
  fi
  if ! kill -0 "$app_pid" 2>/dev/null; then
    echo "mobile_ci: the server stopped before it served:" >&2
    cat "$work/app.log" >&2
    exit 1
  fi
  sleep 1
done
# The bound itself needs a refusal: a process that is alive and silent has answered
# nothing, and without this branch the loop simply ends, the journeys run against a
# port that holds no server, and every flow's own timeout is reported as a device that
# failed rather than a server that never came up. platformkit's harness refuses at this
# same moment, and the log is the only place a configuration that would not bind — a
# database it cannot reach, a NATS it cannot dial — is said at all.
if ! $served; then
  echo "mobile_ci: the kernel built from ${pin} stayed alive for 60 seconds and never answered /health on $port; its log:" >&2
  cat "$work/app.log" >&2
  exit 1
fi

# The second factor, enrolled over the door the phone will use. Everything below
# is a request to the served kernel rather than a row written into its database:
# if the factor routes, the roles or the recovery codes do not behave, this
# harness has to hear it the way a phone would. `api` answers with the status
# code and leaves the body for the step that needs a value out of it.
api() { # api <method> <path> <json or ''> <cookie jar>
  local method="$1" path="$2" body="$3" jar="$4"
  local args=(-sS -o "$work/body" -w '%{http_code}' -X "$method"
    -H 'Content-Type: application/json' -b "$jar" -c "$jar")
  if [ -n "$body" ]; then args+=(-d "$body"); fi
  curl "${args[@]}" "http://localhost:$port$path"
}
refuse() {
  echo "mobile_ci: $1" >&2
  echo "  the server answered:" >&2
  sed 's/^/  /' "$work/body" >&2
  exit 1
}
# One value out of the last answer, as the text the next request sends back.
api_field() {
  python3 - "$work/body" "$1" <<'FIELD'
import json
import sys

sys.stdout.write(str(json.load(open(sys.argv[1]))[sys.argv[2]]))
FIELD
}
: >"$work/admin.jar"
: >"$work/factor.jar"
: >"$work/prove.jar"

echo "mobile_ci: the served kernel mounts the factor routes"
[ "$(api POST /api/v1/auth/login "{\"email\":\"admin@e2e.test\",\"password\":\"$password\"}" "$work/admin.jar")" = "200" ] ||
  refuse "the administrator this script bootstrapped could not sign in"
factors="$(api GET /api/v1/auth/factors '' "$work/admin.jar")"
if [ "$factors" = "404" ]; then
  echo "mobile_ci: the served kernel answers no GET /auth/factors, so it predates the factor migrations (modules/auth/migrations/000031_auth_factors, 000033_first_factor_proofs) and mounts no factor route at all. Point PK_KERNEL_IMAGE at a build that carries them; the journey does not get to skip the second factor." >&2
  exit 1
fi
[ "$factors" = "200" ] || refuse "GET /auth/factors answered $factors rather than 200"

# A second person, so no existing journey gains a step: a recovery code spends
# once and ten journeys sign in as the administrator. The roles are read off the
# administrator's own identity and handed on unchanged, so no role name is written
# into this repository, and the new person is offered the home screen the journeys
# already assert.
#
# Two requests, because the kernel refuses one: POST /user/users answers with a
# User and refuses a body that names roles — "roles belongs to a route of its
# own, not to this one" (kit/crud, at the commit testdata/openapi.json came from)
# — and user-user-roles, POST /user/users/{id}/roles, is the route that owns them
# ("Replaces the roles this person holds"). A person created without roles holds
# none, so the roles step is not one the harness may skip to reach set-password.
echo "mobile_ci: one more person on the same tenant"
api GET /api/v1/auth/me '' "$work/admin.jar" >/dev/null
roles="$(python3 -c 'import json,sys; print(json.dumps(json.load(open(sys.argv[1]))["roles"] or []))' "$work/body")"
[ "$(api POST /api/v1/user/users "{\"email\":\"$factor_email\",\"displayName\":\"Factor E2E\"}" "$work/admin.jar")" = "201" ] ||
  refuse "$factor_email could not be created"
user_id="$(api_field id)"
[ "$(api POST "/api/v1/user/users/$user_id/roles" "{\"roles\":$roles}" "$work/admin.jar")" = "200" ] ||
  refuse "$factor_email could not be given the roles the journeys sign in with"
[ "$(api POST "/api/v1/user/users/$user_id/set-password" "{\"password\":\"$factor_password\"}" "$work/admin.jar")" = "200" ] ||
  refuse "$factor_email could not be given a password"

echo "mobile_ci: enrolling the factor as $factor_email"
[ "$(api POST /api/v1/auth/login "{\"email\":\"$factor_email\",\"password\":\"$factor_password\"}" "$work/factor.jar")" = "200" ] ||
  refuse "$factor_email could not sign in with the password set a moment ago"
[ "$(api POST /api/v1/auth/factors/totp/begin '' "$work/factor.jar")" = "200" ] ||
  refuse "POST /auth/factors/totp/begin did not open an enrolment"
secret="$(api_field secret)"
[ "$(api POST /api/v1/auth/factors/totp/finish "{\"secret\":\"$secret\",\"code\":\"$(python3 scripts/e2e/totp.py "$secret")\"}" "$work/factor.jar")" = "201" ] ||
  refuse "POST /auth/factors/totp/finish refused the code this repository's own prover computed"
# The recovery codes are answered once, in this response and nowhere else.
cp "$work/body" "$work/codes.json"
factor_code="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["codes"][0])' "$work/codes.json")"
[ -n "$factor_code" ] || refuse "the enrolled factor came back with no recovery code to spend"

# Prove the time-based leg while its code is fresh, before Maestro starts: the
# password must be answered by the challenge, and a code computed at this instant
# must be accepted by the operation the phone's code step calls. This leg succeeds,
# and a success commits the DELETE that spends the first-factor proof (modules/auth
# /internal/factors.go's RequireFirstFactorProof), so the window is gone afterwards
# — the device journey re-mints one by giving the password again, which is what the
# journey is for. It spends no recovery code, so what the journey types is still
# good.
echo "mobile_ci: the second factor answers over HTTP"
proof="$(api POST /api/v1/auth/login "{\"email\":\"$factor_email\",\"password\":\"$factor_password\"}" "$work/prove.jar")"
[ "$proof" = "401" ] ||
  refuse "signing in as $factor_email answered $proof, not the 401 that asks for the second factor"
[ "$(api_field detail)" = "$factor_sentence" ] ||
  refuse "the 401 that asked for the second factor did not say what src/core/signInOutcome.ts matches"
[ "$(api POST /api/v1/auth/challenge/verify "{\"email\":\"$factor_email\",\"code\":\"$(python3 scripts/e2e/totp.py "$secret")\"}" "$work/prove.jar")" = "200" ] ||
  refuse "POST /auth/challenge/verify refused a code computed at this instant"

# One contract, both runners: what this script invents it exports, and what the
# job names arrives in the environment it was named in. TITLE stays run.sh's to
# default, so a re-run of one flow alone still lands on a stamped record name.
export SERVER="http://localhost:$port" EMAIL="admin@e2e.test" PASSWORD="$password"
# The three values the second-factor journey reads, named with the rest in
# README's device section. FACTOR_CODE is one of the account's recovery codes rather than
# a live TOTP: run.sh starts Maestro once for every journey and a code is right
# for one 30-second step, so by the time the journey reaches the field it would be
# minutes stale. A recovery code is static and is accepted at the same door by the
# same rules; it is spent once, which is why it belongs to this one person and why
# admin@e2e.test stays password-only for the ten journeys that sign in again.
export TOTP_EMAIL="$factor_email" TOTP_PASSWORD="$factor_password" FACTOR_CODE="$factor_code"
scripts/e2e/run.sh "$apk"

echo "mobile_ci: the journeys ran; the report is at $PK_MOBILE_REPORT"
